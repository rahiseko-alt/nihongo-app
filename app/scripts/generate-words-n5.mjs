#!/usr/bin/env node
// generate-words-n5.mjs
//
// N5タグ（jlptLevel: 'N5'）を持つ漢字の代表単語（word）から、
// 「単語をまるごと書く」練習用の集約データ src/lib/data/kanji/words-n5.js を生成する。
//
// 既存の scripts/generate-kana-46.mjs と同じパターン（個別の u{code}.js を
// 静的 import してまとめる）に従う。ESM は動的パスの静的 import を
// サポートしないため、このスクリプトが実際の import 文をソースとして書き出す。
//
// 単語の構成文字のうち1文字でもストロークデータファイル（u{code}.js）が
// 存在しない場合、その単語は丸ごと除外する（例: 友達=達のファイル欠落、
// 富士山=富のファイル欠落）。SETS/SET_ORDER/KANJI_INDEX には一切触れない
// （getKanjiByChar は使わない。docs/decisions.md の都道府県名セットとの
// KANJI_INDEX 衝突リスクを避けるため）。
//
// 使い方: node scripts/generate-words-n5.mjs

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const KANJI_DIR = path.join(ROOT, 'src', 'lib', 'data', 'kanji');
const OUT_FILE = path.join(KANJI_DIR, 'words-n5.js');

const WORD_RE = /word:\s*'((?:[^'\\]|\\.)*)'/;
const CHAR_RE = /char:\s*'((?:[^'\\]|\\.)*)'/;
const JLPT_RE = /jlptLevel:\s*'N5'/;

function codeOf(ch) {
  return ch.codePointAt(0).toString(16).padStart(5, '0');
}

function slugOf(ch) {
  return `u${codeOf(ch)}`;
}

function constOf(slug) {
  return `KANJI_${slug.toUpperCase()}`;
}

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function collectN5Words() {
  const files = (await fs.readdir(KANJI_DIR)).filter((f) => /^u[0-9a-f]+\.js$/.test(f));
  const words = [];
  for (const f of files) {
    const src = await fs.readFile(path.join(KANJI_DIR, f), 'utf8');
    if (!JLPT_RE.test(src)) continue;
    const wm = src.match(WORD_RE);
    const cm = src.match(CHAR_RE);
    if (!wm || !cm) continue;
    words.push({ file: f, char: cm[1], word: wm[1] });
  }
  return words;
}

async function main() {
  const n5Words = await collectN5Words();

  const valid = [];
  const excluded = [];
  for (const w of n5Words) {
    const chars = Array.from(w.word);
    const missing = [];
    for (const ch of chars) {
      const filePath = path.join(KANJI_DIR, `${slugOf(ch)}.js`);
      if (!(await exists(filePath))) missing.push({ char: ch, expected: `${slugOf(ch)}.js` });
    }
    if (missing.length > 0) {
      excluded.push({ word: w.word, anchorChar: w.char, missing });
    } else {
      valid.push(w);
    }
  }

  // 重複排除した import 文をコードポイント昇順で生成する。
  const uniqueChars = new Map(); // char -> slug
  for (const w of valid) {
    for (const ch of Array.from(w.word)) {
      if (!uniqueChars.has(ch)) uniqueChars.set(ch, slugOf(ch));
    }
  }
  const sortedChars = [...uniqueChars.keys()].sort((a, b) => codeOf(a).localeCompare(codeOf(b)));

  const importLines = sortedChars
    .map(
      (ch) =>
        `import { ${constOf(uniqueChars.get(ch))} } from './${uniqueChars.get(ch)}.js'; // ${ch}`,
    )
    .join('\n');

  const wordEntries = valid
    .map((w) => {
      const chars = Array.from(w.word).map((ch) => constOf(uniqueChars.get(ch)));
      return `  { word: '${w.word}', chars: [${chars.join(', ')}] },`;
    })
    .join('\n');

  const output = `// Auto-generated by scripts/generate-words-n5.mjs
// JLPT N5タグ付き漢字（jlptLevel が N5 のもの）の代表単語（word）を、実際に
// 全文字書く練習向けに集約したデータ。構成文字のストロークデータが1つでも
// 欠けている単語は除外済み（生成時のログで確認できる）。新しいフィールドは
// 追加していない。各要素の chars は既存の u{code}.js が export する
// 漢字データオブジェクトそのもの。
// 注意: このファイル自身は u*.js 命名規則に一致しないため、
// tests/unit/jlptLevel.test.ts の kanjiFiles() 走査対象には含まれない
// （含まれるとこのコメント文字列自体を誤って N5 の1件として数えてしまう）。
${importLines}

export const WORDS_N5 = [
${wordEntries}
];
`;

  await fs.writeFile(OUT_FILE, output, 'utf8');

  // 生成直後に構文確認（PR#8の教訓: 一括書き換えでファイルを壊した事故の再発防止）。
  const mod = await import(`${OUT_FILE}?t=${Date.now()}`);
  if (!Array.isArray(mod.WORDS_N5)) {
    throw new Error('生成された words-n5.js の WORDS_N5 が配列ではありません');
  }

  console.log(
    JSON.stringify(
      {
        n5Candidates: n5Words.length,
        valid: valid.length,
        excluded,
        out: OUT_FILE,
        loadedCount: mod.WORDS_N5.length,
      },
      null,
      2,
    ),
  );
}

main().catch((err) => {
  console.error('[generate-words-n5] 失敗:', err);
  process.exit(1);
});
