#!/usr/bin/env node
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const CSV_PATH = path.join(ROOT, 'docs', 'research', 'kanji-translated-1000-zh-vi-ne.csv');
const KANJI_DIR = path.join(ROOT, 'src', 'lib', 'data', 'kanji');
const IMPORT_SCRIPT = path.join(ROOT, 'scripts', 'import-kanji.mjs');
const PACK_OUT = path.join(KANJI_DIR, 'pack-1000.js');

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i], n = text[i + 1];
    if (q) {
      if (ch === '"' && n === '"') { cell += '"'; i++; }
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (ch !== '\r') cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

function escJs(s) {
  return String(s ?? '').replaceAll('\\', '\\\\').replaceAll("'", "\\'");
}

function codeOf(ch) {
  return ch.codePointAt(0).toString(16).padStart(5, '0');
}

function constOf(slug) {
  return `KANJI_${slug.toUpperCase()}`;
}

async function exists(p) {
  try { await fs.access(p); return true; } catch { return false; }
}

async function patchKanjiFile(filePath, payload) {
  let src = await fs.readFile(filePath, 'utf8');
  const reading = escJs(payload.reading || payload.char);
  const meaning = escJs(payload.jaMeaning || payload.en || payload.char);
  const word = escJs(payload.char);
  src = src.replace(/^(\s*reading:\s*).*,?$/m, `$1'${reading}',`);
  src = src.replace(/^(\s*meaning:\s*).*,?$/m, `$1'${meaning}',`);
  src = src.replace(/^(\s*word:\s*).*,?$/m, `$1'${word}',`);

  const meaningBlock = `  meanings: { ja: '${escJs(payload.jaMeaning)}', en: '${escJs(payload.en)}', zh: '${escJs(payload.zh)}', ko: '${escJs(payload.ko)}', vi: '${escJs(payload.vi)}', ne: '${escJs(payload.ne)}' },\n`;
  if (!src.includes('meanings: {')) {
    src = src.replace(/(  word:[^\n]*\n)/, `$1${meaningBlock}`);
  } else {
    src = src.replace(/meanings:\s*\{[\s\S]*?\},\s*\n/, meaningBlock);
  }

  await fs.writeFile(filePath, src, 'utf8');
}

function runImport(ch) {
  const code = codeOf(ch);
  const slug = `u${code}`;
  execFileSync(process.execPath, [IMPORT_SCRIPT, '--kanji', ch, '--code', code, '--name', slug], {
    cwd: ROOT,
    stdio: 'inherit'
  });
  return slug;
}

function buildPack(rows) {
  const defs = rows.map((r) => ({ ...r, slug: `u${codeOf(r.char)}` }));
  const imports = defs.map((d) => `import { ${constOf(d.slug)} } from './${d.slug}.js';`).join('\n');
  const all = defs.map((d) => constOf(d.slug)).join(', ');
  const popular = defs.slice(0, 500).map((d) => constOf(d.slug)).join(', ');
  const exam = defs.slice(500, 1000).map((d) => constOf(d.slug)).join(', ');
  return `// Auto-generated by scripts/build-and-import-kanji-1000.mjs
// 1000 kanji pack for learning-suite-kanji-foreign.
${imports}

export const KANJI_CORE_1000 = [${all}];
export const KANJI_POPULAR_FOREIGNERS_500 = [${popular}];
export const KANJI_RESIDENT_EXAM_500 = [${exam}];
`;
}

async function main() {
  const csv = parseCsv(await fs.readFile(CSV_PATH, 'utf8'));
  const h = csv[0];
  const ix = Object.fromEntries(h.map((x, i) => [x, i]));
  const rows = csv.slice(1).map((r) => ({
    char: r[ix.char],
    reading: r[ix.reading],
    jaMeaning: r[ix.jaMeaning],
    en: r[ix.en],
    zh: r[ix.zh],
    ko: r[ix.ko],
    vi: r[ix.vi],
    ne: r[ix.ne]
  }));
  if (rows.length !== 1000) throw new Error(`expected 1000 rows, got ${rows.length}`);

  let generated = 0;
  let patched = 0;
  for (const row of rows) {
    const slug = `u${codeOf(row.char)}`;
    const filePath = path.join(KANJI_DIR, `${slug}.js`);
    if (!(await exists(filePath))) {
      runImport(row.char);
      generated++;
    }
    await patchKanjiFile(filePath, row);
    patched++;
  }

  await fs.writeFile(PACK_OUT, buildPack(rows), 'utf8');
  console.log(JSON.stringify({ generated, patched, pack: PACK_OUT }, null, 2));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
