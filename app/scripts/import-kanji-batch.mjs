#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const IMPORT_SCRIPT = path.join(ROOT, 'scripts', 'import-kanji.mjs');
const KANJI_DIR = path.join(ROOT, 'src', 'lib', 'data', 'kanji');
const COLLECTIONS_PATH = path.join(KANJI_DIR, 'batch-collections.js');

// 推定根拠:
// - 「外国人に人気」: 日本滞在中の生活・移動・買い物で高頻度に目にする基礎漢字
// - 「在留外国人の試験問題」: JLPT N5/N4 近辺の初級学習で高頻度に扱われる基礎漢字
// ※ JLPT は公式の語彙/漢字リストを公開していないため、実務上の代表的学習範囲を採用
const POPULAR_FOREIGNERS_50 = [
  '日', '本', '人', '今', '何', '時', '分', '円', '百', '千',
  '万', '駅', '電', '車', '道', '口', '入', '出', '北', '南',
  '東', '西', '右', '左', '前', '後', '上', '下', '中', '外',
  '内', '名', '国', '語', '英', '会', '社', '店', '買', '食',
  '飲', '水', '火', '木', '金', '土', '雨', '空', '海', '山'
];

const RESIDENT_EXAM_50 = [
  '一', '二', '三', '四', '五', '六', '七', '八', '九', '十',
  '百', '千', '万', '今', '何', '午', '半', '毎', '先', '生',
  '学', '校', '文', '字', '読', '書', '聞', '話', '見', '行',
  '来', '帰', '休', '友', '父', '母', '子', '男', '女', '家',
  '室', '町', '村', '県', '京', '都', '語', '白', '天', '気'
];

function codeOf(ch) {
  return ch.codePointAt(0).toString(16).padStart(5, '0');
}

function slugOf(ch) {
  return `u${codeOf(ch)}`;
}

function constNameOfSlug(slug) {
  return `KANJI_${slug.toUpperCase()}`;
}

function runImport(ch) {
  const code = codeOf(ch);
  const slug = slugOf(ch);
  const args = [
    IMPORT_SCRIPT,
    '--kanji', ch,
    '--code', code,
    '--name', slug,
    '--force'
  ];
  execFileSync(process.execPath, args, {
    cwd: ROOT,
    stdio: 'inherit'
  });
}

function buildCollectionsFile(popular, exam) {
  const allSlugs = [...new Set([...popular, ...exam].map((ch) => slugOf(ch)))];
  const importLines = allSlugs
    .map((slug) => `import { ${constNameOfSlug(slug)} } from './${slug}.js';`)
    .join('\n');

  const arrLine = (chars) =>
    chars.map((ch) => constNameOfSlug(slugOf(ch))).join(', ');

  return `// Auto-generated by scripts/import-kanji-batch.mjs
// Do not hand-edit this file.
${importLines}

export const KANJI_POPULAR_FOREIGNERS_50 = [${arrLine(popular)}];
export const KANJI_RESIDENT_EXAM_50 = [${arrLine(exam)}];
`;
}

async function main() {
  const allChars = [...new Set([...POPULAR_FOREIGNERS_50, ...RESIDENT_EXAM_50])];
  console.log(`[batch] importing ${allChars.length} unique kanji...`);
  for (const ch of allChars) {
    console.log(`[batch] ${ch} (${codeOf(ch)})`);
    runImport(ch);
  }

  await fs.mkdir(KANJI_DIR, { recursive: true });
  const collections = buildCollectionsFile(POPULAR_FOREIGNERS_50, RESIDENT_EXAM_50);
  await fs.writeFile(COLLECTIONS_PATH, collections, 'utf8');
  console.log(`[batch] wrote collections: ${COLLECTIONS_PATH}`);
}

main().catch((err) => {
  console.error('[batch] failed:', err);
  process.exit(1);
});

